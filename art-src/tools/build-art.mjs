/**
 * art-src/gen/*.png (ChatGPT originals) -> public/art/*.webp (what ships).
 *
 * Why one script: every image needs the same decision made the same way -
 * cut-outs go through cutout.mjs (copied from BTTRURSLF-v2: trims, snaps and
 * erodes the alpha, and pulls the glow ChatGPT paints round a subject back
 * out of the edge pixels), opaque plates and textures are only resized and
 * encoded, comps never ship. And anything the manifest names that was never
 * generated gets a clearly labelled placeholder instead of a broken image,
 * listed in art-src/MISSING.md, so the site always builds and the gap is
 * visible.
 *
 * usage: node art-src/tools/build-art.mjs [--only name,name] [--force]
 * cutout.mjs loads images over http, so this serves the repo root itself (a
 * few lines of node:http - no dev server or index.html needed).
 */
import { execFileSync } from 'node:child_process';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ITEMS } from '../manifest.mjs';

const GEN = 'art-src/gen', OUT = 'public/art';
const args = process.argv.slice(2);
const only = args.includes('--only') ? new Set(args[args.indexOf('--only') + 1].split(',')) : null;
const force = args.includes('--force');

// Largest edge per group: plates and bands are full-bleed (1920 screens; the
// originals are ~1672 wide, never upscaled), objects sit at mid depth, plants
// are drawn small in the garden and the plan.
const MAX = { plates: 2400, bands: 2400, scenes: 1600, soil: 1400, tex: 1024, pre: 900, ui: 1000, demo: 1920, plants: 720 };
const outPath = (it) => it.group === 'plants'
  ? path.join(OUT, 'plants', `${it.name.replace(/^plant-/, '')}.webp`)
  : path.join(OUT, `${it.name}.webp`);

fs.mkdirSync(path.join(OUT, 'plants'), { recursive: true });
const items = ITEMS.filter((it) => it.group !== 'comps' && (!only || only.has(it.name)));

const PORT = 5199;
const TYPES = { '.png': 'image/png', '.json': 'application/json' };
const server = http.createServer((req, res) => {
  const file = path.join(process.cwd(), decodeURIComponent(req.url.split('?')[0]));
  if (!file.startsWith(process.cwd()) || !fs.existsSync(file)) { res.writeHead(404).end(); return; }
  res.writeHead(200, { 'content-type': TYPES[path.extname(file)] || 'application/octet-stream' });
  fs.createReadStream(file).pipe(res);
});
await new Promise((r) => server.listen(PORT, "127.0.0.1", r));
const missing = [];
try {
  for (const it of items) {
    const src = path.join(GEN, `${it.name}.png`);
    const out = outPath(it);
    if (!force && fs.existsSync(out) && fs.existsSync(src) && fs.statSync(out).mtimeMs > fs.statSync(src).mtimeMs) continue;
    const max = MAX[it.group] || 1600;
    if (!fs.existsSync(src)) {
      missing.push(it);
      await placeholder(it, out, max);
      continue;
    }
    if (it.cutout) {
      const base = out.replace(/\.webp$/, '');
      execFileSync(process.execPath, ['art-src/tools/cutout.mjs', `http://127.0.0.1:${PORT}`, src.replaceAll('\\', '/'), base, '--max', String(max), '--q', '0.86', '--islands'], { stdio: 'inherit' });
      fs.rmSync(`${base}.png`, { force: true }); // cutout.mjs also writes the cleaned PNG; the original in gen/ is the source of truth
    } else {
      await sharp(src).resize({ width: max, height: max, fit: 'inside', withoutEnlargement: true }).webp({ quality: 84 }).toFile(out);
      console.log(src, '->', out);
    }
  }
} finally {
  server.close();
}

fs.writeFileSync('art-src/MISSING.md', `# Art still needed\n\nGenerated by build-art.mjs. Each of these ships as a labelled placeholder.\n\n${missing.length ? missing.map((it) => `- \`${it.name}\` (${it.group}): ${it.prompt.slice(0, 140)}...`).join('\n') : 'None - every image in art-src/manifest.mjs exists.'}\n`);
console.log(missing.length ? `${missing.length} placeholders: ${missing.map((m) => m.name).join(', ')}` : 'no placeholders');

async function placeholder(it, out, max) {
  const [w, h] = (it.size || '1024x1024').split('x').map(Number);
  const s = Math.min(1, max / Math.max(w, h));
  const W = Math.round(w * s), H = Math.round(h * s);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
    <rect width="100%" height="100%" fill="${it.cutout ? 'none' : '#3E4A59'}"/>
    <rect x="8%" y="8%" width="84%" height="84%" rx="24" fill="#3E4A59" fill-opacity="0.85" stroke="#E8B04A" stroke-width="4" stroke-dasharray="16 10"/>
    <text x="50%" y="48%" font-family="sans-serif" font-size="${Math.round(W / 22)}" fill="#ECE6DA" text-anchor="middle">PLACEHOLDER</text>
    <text x="50%" y="58%" font-family="sans-serif" font-size="${Math.round(W / 30)}" fill="#E8B04A" text-anchor="middle">${it.name}</text>
  </svg>`;
  await sharp(Buffer.from(svg)).webp({ quality: 80 }).toFile(out);
  console.log('PLACEHOLDER', out);
}
